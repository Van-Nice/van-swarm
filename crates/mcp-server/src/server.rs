    async fn get_prompt(
        &self,
        request: GetPromptRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<GetPromptResult, McpError> {
        let args = request.arguments.unwrap_or_default();
        let get = |key: &str| {
            args.get(key).and_then(|v| v.as_str()).unwrap_or("").to_string()
        };

        match request.name.as_str() {
            "new_agent_scaffold" => {
                let name = get("name");
                if name.is_empty() {
                    return Err(McpError::invalid_params(
                        "'name' argument is required for new_agent_scaffold.",
                        None,
                    ));
                }
                let model = get("model");
                let model = if model.is_empty() { "claude-opus-4-6".to_string() } else { model };
                let text = agent_scaffold_prompt(&name, &model);
                Ok(GetPromptResult {
                    description: Some(format!(
                        "VanSwarm ReAct agent scaffold for '{name}' using '{model}'"
                    )),
                    messages: vec![PromptMessage::new_text(PromptMessageRole::User, text)],
                })
            }

            "new_workflow_scaffold" => {
                let name = get("name");
                if name.is_empty() {
                    return Err(McpError::invalid_params(
                        "'name' argument is required for new_workflow_scaffold.",
                        None,
                    ));
                }
                let text = workflow_scaffold_prompt(&name);
                Ok(GetPromptResult {
                    description: Some(format!("VanSwarm workflow scaffold for '{name}'")),
                    messages: vec![PromptMessage::new_text(PromptMessageRole::User, text)],
                })
            }

            "add_tool_scaffold" => {
                let tool_name = get("tool_name");
                if tool_name.is_empty() {
                    return Err(McpError::invalid_params(
                        "'tool_name' argument is required for add_tool_scaffold.",
                        None,
                    ));
                }
                let text = tool_scaffold_prompt(&tool_name);
                Ok(GetPromptResult {
                    description: Some(format!("VanSwarm tool scaffold for '{tool_name}'")),
                    messages: vec![PromptMessage::new_text(PromptMessageRole::User, text)],
                })
            }

            other => Err(McpError::invalid_params(
                format!(
                    "Unknown prompt '{other}'. Available prompts: \
                     new_agent_scaffold, new_workflow_scaffold, add_tool_scaffold."
                ),
                None,
            )),
        }
    }
