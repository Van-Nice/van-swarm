/// Parameters for `vanswarm_run_agent`.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct RunAgentParams {
    /// The user prompt or task description for the agent to solve.
    pub prompt: String,

    /// Optional system prompt to set the agent's persona or constraints.
    /// Example: "You are a concise Rust expert. Use tools where appropriate."
    #[serde(default)]
    pub system_prompt: Option<String>,

    /// LLM model override. Defaults to the server-detected default.
    /// Examples: "claude-opus-4-6", "gpt-4o", "gemini-2.0-flash"
    #[serde(default)]
    pub model: Option<String>,

    /// Maximum number of ReAct iterations before the agent gives up.
    /// Default: 10. Lower for faster responses; raise for complex multi-step tasks.
    #[serde(default)]
    pub max_iterations: Option<u32>,
}

/// Parameters for `vanswarm_memory_store`.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct MemoryStoreParams {
    /// The fact, observation, or event to remember.
    pub content: String,
}

/// Parameters for `vanswarm_memory_search`.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct MemorySearchParams {
    /// Full-text search query (case-insensitive substring match).
    pub query: String,

    /// Maximum number of results to return. Default: 10.
    #[serde(default)]
    pub limit: Option<u32>,
}

/// Parameters for `vanswarm_memory_recent`.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct MemoryRecentParams {
    /// Maximum number of entries to return, newest first. Default: 10.
    #[serde(default)]
    pub limit: Option<u32>,
}

/// Empty parameter struct for `vanswarm_framework_info`.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct NoParams {}

