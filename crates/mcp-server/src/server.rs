const DOCS_URI_PREFIX: &str = "vanswarm://docs/";

/// Walk `root` recursively and return all `.md` files as MCP `Resource` values.
///
/// Resources are sorted by URI for deterministic listing order.
fn collect_doc_resources(root: &std::path::Path) -> Vec<rmcp::model::Resource> {
    let mut resources = Vec::new();
    collect_recursive(root, root, &mut resources);
    resources.sort_by(|a, b| a.uri.cmp(&b.uri));
    resources
}

fn collect_recursive(
    root: &std::path::Path,
    dir: &std::path::Path,
    acc: &mut Vec<rmcp::model::Resource>,
) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_recursive(root, &path, acc);
        } else if path.extension().map_or(false, |e| e == "md") {
            let relative = path.strip_prefix(root).unwrap_or(&path);
            // Use forward slashes in URIs even on Windows.
            let rel_str = relative
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            let uri = format!("{DOCS_URI_PREFIX}{rel_str}");
            let description = path
                .file_stem()
                .map(|s| s.to_string_lossy().replace(['-', '_'], " "));
            let raw = RawResource {
                uri: uri.clone(),
                name: rel_str,
                title: None,
                description,
                mime_type: Some("text/markdown".to_string()),
                size: path.metadata().ok().map(|m| m.len() as u32),
                icons: None,
                meta: None,
            };
            acc.push(raw.no_annotation());
        }
    }
}

/// Resolve a `vanswarm://docs/<path>` URI to a safe filesystem path under `docs_root`.
///
/// Returns `None` if:
/// - The URI does not start with `vanswarm://docs/`.
/// - The path contains `..`, a leading `/`, or a null byte.
/// - The canonicalized path is outside `docs_root`.
fn resolve_doc_uri(docs_root: &std::path::Path, uri: &str) -> Option<std::path::PathBuf> {
    let relative = uri.strip_prefix(DOCS_URI_PREFIX)?;

    // Reject obvious traversal attempts before touching the filesystem.
    if relative.contains("..") || relative.starts_with('/') || relative.contains('\0') {
        return None;
    }

    // Convert URI-style forward slashes to platform path separators.
    let rel_path: std::path::PathBuf = relative.split('/').collect();
    let full_path = docs_root.join(&rel_path);

    // Canonicalize both paths so symlinks cannot escape the root.
    let canonical_root = std::fs::canonicalize(docs_root).ok()?;
    let canonical_path = std::fs::canonicalize(&full_path).ok()?;

    if canonical_path.starts_with(&canonical_root) {
        Some(full_path)
    } else {
        None
    }
}

